#!/usr/bin/env python3
"""Read-only export of the demo database (tools/demo-data) into docs/design/mobile/demo-data.js (file:// friendly).
Design material only. Opens the demo DB with mode=ro; never touches the real app database."""
import json, sqlite3, sys
from pathlib import Path
db = Path.home() / ".local/share/arthur-demo/dev.kaloyan.arthur/arthur.db"
c = sqlite3.connect(f"file:{db}?mode=ro", uri=True); c.row_factory = sqlite3.Row
q = lambda s: [dict(r) for r in c.execute(s)]
caps = q("SELECT id, source, content, created_at at, (SELECT count(*) FROM distillation_runs d WHERE d.capture_id=captures.id) ran FROM captures ORDER BY created_at DESC")
objs = q("""SELECT o.id, o.kind, o.title, o.body, o.created_at, o.current_revision_id cur,
  s.capture_id cap, s.source_start ss, s.source_end se,
  (SELECT count(*) FROM thought_revisions r WHERE r.object_id=o.id) revs
  FROM knowledge_objects o JOIN object_sources s ON s.object_id=o.id ORDER BY o.created_at DESC""")
rels = q("SELECT id, kind, source_object_id s, target_object_id t, origin, created_at at FROM relations ORDER BY created_at")
revs = q("SELECT id, object_id o, seq, kind, title, body, origin, created_at at, capture_id cap, source_start ss, source_end se FROM thought_revisions ORDER BY seq")
par = q("SELECT child_revision_id c, parent_revision_id p FROM revision_parents")
payload = json.dumps(dict(captures=caps, objects=objs, relations=rels, revisions=revs, parents=par), ensure_ascii=False)
open("demo-data.js", "w").write("/* generated by export_demo.py from the demo database. Design material, not product code. */\nwindow.DEMO = " + payload + ";\n")
print({k: len(v) for k, v in dict(c=caps, o=objs, r=rels, v=revs, p=par).items()})
