//! Markdown for the evaluation report and the human review packet.

use super::metrics::Rows;
use super::runner::{deterministic, identity_result};
use super::{IdCase, RevCase};

pub fn table(title: &str, rows: &Rows) -> String {
    let mut out = format!("#### {title}\n\n| metric | result |\n|---|---|\n");
    for (name, rate) in &rows.0 {
        out.push_str(&format!("| {name} | {} |\n", rate.show()));
    }
    out.push('\n');
    out
}

/// Every case, with the implementer's label and what the deterministic layers did, and empty columns for an independent reviewer.
pub fn review_packet(revision: &[(&str, &[RevCase])], identity: &[(&str, &[IdCase])]) -> String {
    let mut out = String::from("# Phase 4C review packet (for independent human adjudication)\n\n");
    out.push_str("Generated by `cargo test --lib synthesis::eval -- --nocapture` with `ARTHUR_EVAL_WRITE=<dir>`. **Author labels are the implementer's (an AI assistant's) and are not ground truth.** ");
    out.push_str("Fill in the last two columns without looking at the author label column first; disagreements are the finding.\n\n");
    for (split, cases) in revision {
        out.push_str(&format!("## Revision cases: {split}\n\n| id | lang | change | existing text | new note | proposed text | author label | author class | validator | reviewer verdict (safe/unsafe) | reviewer note |\n|---|---|---|---|---|---|---|---|---|---|---|\n"));
        for c in cases.iter() {
            let det = deterministic(c).err().unwrap_or("accepted");
            out.push_str(&format!(
                "| {} | {} | {} | {} | {} | {} | {} | {} | {} | | |\n",
                c.id,
                c.lang,
                c.change,
                esc(&c.base),
                esc(&c.claim),
                esc(&c.draft.revised_body),
                c.label,
                c.unsafe_class.as_deref().unwrap_or("-"),
                det
            ));
        }
        out.push('\n');
    }
    for (split, cases) in identity {
        out.push_str(&format!("## Identity cases: {split}\n\n| id | lang | new note | candidates | author expectation | resolver result | reviewer expectation | reviewer note |\n|---|---|---|---|---|---|---|---|\n"));
        for c in cases.iter() {
            out.push_str(&format!(
                "| {} | {} | {} | {} | {} | {} | | |\n",
                c.id,
                c.lang,
                esc(&c.claim),
                c.candidates.join(","),
                c.expect,
                identity_result(c)
            ));
        }
        out.push('\n');
    }
    out
}

fn esc(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}
