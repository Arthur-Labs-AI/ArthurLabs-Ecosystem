/**
 * Tauri-backed client for Android (later iOS).
 * Captures are persisted by the native layer in the app's private SQLite database.
 * Voice capture records the microphone natively, transcribes in the cloud, and stores
 * only the transcript. BLE and the sync outbox will diverge from the desktop client here.
 */
export function createMobileClient(call?: Invoke): ArthurClient {
  return {
    kind: "mobile",
    capabilities: { voiceCapture: true, speechOutput: true },
    getRuntimeInfo: () => fetchRuntimeInfo(call),
    createCapture: (input) => createCaptureOverIpc(input, call),
    getCaptures: (captureIds) => getCapturesOverIpc(captureIds, call),
    listCaptures: (scope) => listCapturesOverIpc(scope, call),
    startVoiceCapture: () => startVoiceCaptureOverIpc(call),
    finishVoiceCapture: (projectId) => finishVoiceCaptureOverIpc(projectId, call),
    cancelVoiceCapture: () => cancelVoiceCaptureOverIpc(call),
    retryVoiceTranscription: (projectId) => retryVoiceTranscriptionOverIpc(projectId, call),
    discardVoiceRecording: () => discardVoiceRecordingOverIpc(call),
    getMicrophonePermission: () => getMicrophonePermissionOverIpc(call),
    openAppSettings: () => openAppSettingsOverIpc(call),
    distillCapture: (captureId) => distillCaptureOverIpc(captureId, call),
    listKnowledgeObjects: (scope) => listKnowledgeObjectsOverIpc(scope, call),
    listOrganizationStates: (scope) => listOrganizationStatesOverIpc(scope, call),
    getKnowledgeSummaries: (objectIds, scope) => getKnowledgeSummariesOverIpc(objectIds, scope, call),
    createRelation: (input) => createRelationOverIpc(input, call),
    listRelations: () => listRelationsOverIpc(call),
    getObjectRelations: (objectId, filter) => getObjectRelationsOverIpc(objectId, filter, call),
    getObjectNeighbors: (objectId, filter) => getObjectNeighborsOverIpc(objectId, filter, call),
    inferRelations: (objectIds, scope) => inferRelationsOverIpc(objectIds, scope, call),
    getObjectLineage: (objectId) => getObjectLineageOverIpc(objectId, call),
    listRevisions: (objectId) => listRevisionsOverIpc(objectId, call),
    getRevision: (revisionId) => getRevisionOverIpc(revisionId, call),
    getRevisionParents: (revisionId) => getRevisionParentsOverIpc(revisionId, call),
    getRevisionChildren: (revisionId) => getRevisionChildrenOverIpc(revisionId, call),
    updateKnowledgeObject: (objectId, changes) => updateKnowledgeObjectOverIpc(objectId, changes, call),
    createRevisionFrom: (input) => createRevisionFromOverIpc(input, call),
    mergeRevisions: (input) => mergeRevisionsOverIpc(input, call),
    diffRevisions: (oldRevisionId, newRevisionId) => diffRevisionsOverIpc(oldRevisionId, newRevisionId, call),
    listProjects: (options) => listProjectsOverIpc(options, call),
    getProject: (projectId) => getProjectOverIpc(projectId, call),
    createProject: (name) => createProjectOverIpc(name, call),
    renameProject: (projectId, name) => renameProjectOverIpc(projectId, name, call),
    archiveProject: (projectId) => archiveProjectOverIpc(projectId, call),
    restoreProject: (projectId) => restoreProjectOverIpc(projectId, call),
    moveCapture: (captureId, projectId) => moveCaptureOverIpc(captureId, projectId, call),
    moveKnowledgeObject: (objectId, projectId) => moveKnowledgeObjectOverIpc(objectId, projectId, call),
    getActiveProject: () => getActiveProjectOverIpc(call),
    setActiveProject: (projectId) => setActiveProjectOverIpc(projectId, call),
    getProjectGraph: (projectId) => getProjectGraphOverIpc(projectId, call),
    ask: (query) => askOverIpc(query, call),
    getSemanticRecallStatus: () => getSemanticRecallStatusOverIpc(call),
    setSemanticRecallEnabled: (enabled) => setSemanticRecallEnabledOverIpc(enabled, call),
    purgeSemanticIndex: () => purgeSemanticIndexOverIpc(call),
    getAiConfig: () => getAiConfigOverIpc(call),
    setCredential: (provider, secret) => setCredentialOverIpc(provider, secret, call),
    hasCredential: (provider) => hasCredentialOverIpc(provider, call),
    deleteCredential: (provider) => deleteCredentialOverIpc(provider, call),
    testProvider: (capability) => testProviderOverIpc(capability, call),
    completeSetup: () => completeSetupOverIpc(call),
    speakText: (input) => speakTextOverIpc(input, call),
    testVoice: () => testVoiceOverIpc(call),
    stopSpeech: () => stopSpeechOverIpc(call),
    getSpeechStatus: () => getSpeechStatusOverIpc(call),
  };
}
